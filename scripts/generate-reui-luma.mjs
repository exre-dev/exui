import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { restoreReuiSnapshot } from './reui-restore.mjs'

const root = path.resolve(import.meta.dirname, '..')
const componentRoot = path.join(root, 'packages/components/src/components')
await restoreReuiSnapshot()
const upstreamCss = readFileSync(path.join(root, 'packages/components/upstream/reui/style-luma.css'), 'utf8').replaceAll('\r\n', '\n')
const classes = new Set()
function collect(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const filename = path.join(dir, entry.name)
    if (entry.isDirectory()) collect(filename)
    else if (/\.tsx?$/.test(entry.name)) {
      for (const match of readFileSync(filename, 'utf8').matchAll(/\bcn-[\w-]+\b/g)) classes.add(match[0])
    }
  }
}
collect(componentRoot)
// Trace names these slots for composition, but upstream Luma provides recipes
// only for its six painted parts. Their geometry stays in the source classes.
const unstyledTraceSlots = new Set(['cn-trace-collapsible', 'cn-trace-title', 'cn-trace-description'])
for (const name of unstyledTraceSlots) if (!classes.has(name)) throw new Error(`Missing Trace slot marker ${name}`)
const rules = [...classes].filter(name => !unstyledTraceSlots.has(name)).sort().map((name) => {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const match = upstreamCss.match(new RegExp(`\\.${escaped}\\s*\\{([^}]*)\\}`))
  if (!match) throw new Error(`Missing pinned Luma recipe for ${name}`)
  // Adapt only the owned ordinary radius; the pinned upstream remains intact.
  const recipe = name === 'cn-questionnaire-choice-indicator'
    ? match[1].replace('rounded-[5px]', 'rounded-[0.3125rem]')
    : match[1]
  return `  .${name} {${recipe}}`
})
const css = `/* Selected Luma recipes for the pinned ReUI source; generated by scripts/generate-reui-luma.mjs. */\n@layer components {\n${rules.join('\n\n')}\n}\n`
const filename = path.join(root, 'packages/components/src/reui-luma.css')
if (process.argv.includes('--check')) {
  if (readFileSync(filename, 'utf8').replaceAll('\r\n', '\n') !== css) throw new Error('ReUI Luma CSS is stale')
} else writeFileSync(filename, css)
console.log(`ReUI Luma recipes: ${rules.length}`)
