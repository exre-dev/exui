import { readFile, readdir, mkdir, writeFile } from "node:fs/promises"
import { createHash } from "node:crypto"
import { existsSync } from "node:fs"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"
import { capabilitySkillOverlays, renderBounded } from "../exui-capabilities.mjs"

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const skillRoot = path.join(repoRoot, "skills/exui")
const sourceRoot = path.join(repoRoot, "resources/components")
const outputRoot = path.join(skillRoot, "references/components")
const posix = (value) => value.replaceAll("\\", "/")
const canonical = (value) => value.replaceAll("\r\n", "\n")
const digest = (value) => createHash("sha256").update(canonical(value)).digest("hex")

function catalogFor(files) {
  return [
    "<!-- Generated by scripts/exui-skill/sync-references.mjs. -->", "", "# Local component catalog", "",
    "Use this catalog to choose a family and read its when-to-use guidance. Each family page links its downloaded c-* pattern descriptions. For exact ExUI exports and props, read [ExUI contracts](exui/setup.md) and the [export inventory](generated/component-exports.md).", "",
    ...files.filter((file) => !file.includes("/")).map((file) => `- [${path.posix.basename(file, ".md")}](components/${file})`), "",
  ].join("\n")
}

async function documentFiles(directory) {
  return (await readdir(directory, { recursive: true })).filter((file) => file.endsWith(".md")).map(posix).sort()
}

async function verifyOverlays(targetSkillRoot, overlays) {
  const directory = path.join(targetSkillRoot, "references/components")
  for (const [family, content] of overlays) {
    const filename = path.join(directory, `${family}.md`)
    const actual = await readFile(filename, "utf8").catch(() => "")
    if (!actual || canonical(actual) !== renderBounded(actual, content, "skill")) throw new Error(`Stale/missing ExUI overlay: ${filename}`)
  }
  for (const file of (await documentFiles(directory)).filter((file) => !file.includes("/"))) {
    if (overlays.has(file.slice(0, -3))) continue
    if (/<!-- exui-capabilities:(?:begin|end):skill -->/.test(await readFile(path.join(directory, file), "utf8"))) throw new Error(`Stale ExUI overlay in unregistered family: ${file}`)
  }
}

async function referenceLock(targetSkillRoot, mode, overlays, { skipOverlayCheck = false } = {}) {
  const directory = path.join(targetSkillRoot, "references/components")
  const lockFile = path.join(targetSkillRoot, "references/generated/component-reference-lock.json")
  const present = await documentFiles(directory)
  if (!skipOverlayCheck && (mode === "--check" || mode === "--lock")) await verifyOverlays(targetSkillRoot, overlays)
  let locked
  if (mode === "--check") {
    locked = JSON.parse(await readFile(lockFile, "utf8"))
    if (locked?.schemaVersion !== 1 || !locked.files || typeof locked.files !== "object" || Array.isArray(locked.files) || !/^[a-f0-9]{64}$/.test(locked.catalogSha256)) throw new Error("Invalid component reference lock")
    const names = Object.keys(locked.files).sort()
    for (const name of names) {
      if (!name.endsWith(".md") || name.includes("\\") || path.posix.isAbsolute(name) || /^[a-z]:/i.test(name) || name.split("/").some((part) => !part || part === "." || part === "..") || !/^[a-f0-9]{64}$/.test(locked.files[name])) throw new Error(`Invalid locked reference: ${name}`)
    }
    if (names.join("\0") !== present.join("\0")) throw new Error("Reference inventory mismatch")
  }
  if (!present.length) throw new Error("No generated component references found")
  const catalog = await readFile(path.join(targetSkillRoot, "references/components.md"), "utf8")
  if (canonical(catalog) !== catalogFor(present)) throw new Error("Generated reference catalog mismatch")
  const files = Object.fromEntries(await Promise.all(present.map(async (file) => [file, digest(await readFile(path.join(directory, file), "utf8"))])))
  const snapshot = { schemaVersion: 1, source: "https://reui.io/components", files, catalogSha256: digest(catalog) }
  if (mode === "--check") {
    for (const file of present) if (locked.files[file] !== files[file]) throw new Error(`Reference hash mismatch: ${file}`)
    if (locked.catalogSha256 !== snapshot.catalogSha256) throw new Error("Reference catalog hash mismatch")
  } else {
    await mkdir(path.dirname(lockFile), { recursive: true })
    await writeFile(lockFile, `${JSON.stringify(snapshot, null, 2)}\n`, "utf8")
  }
  return { count: present.length, snapshot, lockFile, present }
}

export async function prepareOverlayLockRefresh(targetSkillRoot, pending) {
  const verified = await referenceLock(targetSkillRoot, "--check", null, { skipOverlayCheck: true })
  const files = { ...verified.snapshot.files }
  for (const [name, expected] of pending) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*\.md$/.test(name) || !verified.present.includes(name)) throw new Error(`Invalid overlay refresh target: ${name}`)
    files[name] = digest(expected)
  }
  return { lockFile: verified.lockFile, snapshot: { ...verified.snapshot, files } }
}

export function localizeReferences(markdown, relativeFile, downloadedFiles) {
  let linkCount = 0
  const result = markdown.replace(/<?https:\/\/reui\.io\/components\/[^\s)<>[\]"`]+>?/g, (match, offset, source) => {
    const address = match.replace(/^<|>$/g, "")
    const url = new URL(address)
    const component = decodeURIComponent(url.pathname.slice("/components/".length))
    if (!url.pathname.startsWith("/components/") || component.split("/").some((part) => part === ".." || part === ".") || component.includes("\\")) {
      throw new Error(`Invalid component path in ${relativeFile}: ${address}`)
    }
    const target = [component, `${component}.md`, `${component}/index.md`].find((candidate) => downloadedFiles.has(candidate))
    if (!target) throw new Error(`Missing downloaded target in ${relativeFile}: ${address}`)
    let destination = path.posix.relative(path.posix.dirname(relativeFile), target)
    if (!destination.startsWith(".")) destination = `./${destination}`
    destination += url.hash
    linkCount++
    return source[offset - 1] === "(" ? destination : `[local reference](${destination})`
  })
  return { markdown: result, linkCount }
}

export function consumerGuidance(markdown) {
  return markdown
    .replace(/^> Upstream ReUI pattern reference\./gm, "> Pattern reference.")
    .replaceAll("Base/Radix alternatives and registry metadata do not define ExUI exports.", "Base/Radix alternatives do not define ExUI exports.")
    .replace(/^- (?:Upstream registry item \(provenance\)|Registry item):.*\n/gm, "")
    .replace(/^- Docs[^\n]*https:\/\/reui\.io[^\n]*\n/gm, "")
    .replace(/\[([^\]]+)\]\(https:\/\/reui\.io\/[^)]+\)/g, "$1")
    .replace(/@\/components\/(?:reui|ui)\/[a-z0-9/-]+/g, "@exre/exui")
    .replace(/\bReUI(?:-derived|-based)?\b/g, "upstream")
}

export function adaptDocument(markdown, relativeFile, files) {
  const localized = localizeReferences(markdown.replaceAll("\r\n", "\n"), relativeFile, files)
  const setup = posix(path.relative(path.dirname(path.join(outputRoot, relativeFile)), path.join(skillRoot, "references/exui/setup.md")))
  const provenance = `> Pattern reference. Read [ExUI contracts](${setup}) before implementation; Base/Radix alternatives do not define ExUI exports.\n\n`
  const content = localized.markdown
    .replace(/[ \t]+$/gm, "")
    .replace(/^- MCP:.*\n/gm, "")
    .replace(/\s+\(`(?:get_component|get_example|get_examples|get_block)\([^`]*\)`\)/g, "")
    .replace(/^- Registry item:/gm, "- Upstream registry item (provenance):")
    .replace(/\n## Install[^\n]*\n[\s\S]*?(?=\n## |$)/g, `\n## ExUI adaptation\n\nCompose this pattern from public ExUI components; see [setup](${setup}). This example is not an exported component or a complete TSX source file.\n`)
    .replace(/\nEvery ReUI item has a twin[^\n]*(?:\n|$)/g, "\n")
  return { markdown: consumerGuidance(`<!-- Generated from resources/components/${posix(relativeFile)} by scripts/exui-skill/sync-references.mjs. -->\n${provenance}${content.trimEnd()}\n`), linkCount: localized.linkCount }
}

export async function synchronize(mode, options = {}) {
  if (!["--write", "--check", "--lock"].includes(mode)) throw new Error("usage: node scripts/exui-skill/sync-references.mjs (--write | --check | --lock)")
  const sourceDirectory = options.sourceRoot ?? sourceRoot
  const targetSkillRoot = options.skillRoot ?? skillRoot
  const targetOutputRoot = path.join(targetSkillRoot, "references/components")
  const overlays = options.overlays ?? await capabilitySkillOverlays()
  if (mode === "--lock") {
    const result = await referenceLock(targetSkillRoot, mode, overlays)
    console.log(`--lock: ${result.count} reviewed component references`)
    return
  }
  if (mode === "--check") await referenceLock(targetSkillRoot, mode, overlays)
  let files
  try { files = await documentFiles(sourceDirectory) } catch (error) {
    if (mode !== "--check" || error.code !== "ENOENT") throw error
    console.log("--check: locked references verified; optional download archive absent")
    return
  }
  if (!files.length) throw new Error("No downloaded component documents found")
  const partialArchive = existsSync(path.join(sourceDirectory, ".partial"))
  // A partial archive may replace only its downloaded pages. Trust all other
  // generated references only after checking their complete reviewed lock.
  if (partialArchive && mode === "--write") await referenceLock(targetSkillRoot, "--check", overlays)
  const present = await documentFiles(targetOutputRoot).catch((error) => {
    if (mode === "--write" && error.code === "ENOENT") return []
    throw error
  })
  const downloaded = new Set(partialArchive ? [...present, ...files] : files)
  // Resolve every target before any write, so an incomplete download fails without publishing broken links.
  const outputs = await Promise.all(files.map(async (file) => {
    const adapted = adaptDocument(await readFile(path.join(sourceDirectory, file), "utf8"), file, downloaded)
    const overlay = file.endsWith(".md") && !file.includes("/") ? overlays.get(file.slice(0, -3)) : null
    return { file, ...adapted, markdown: overlay ? renderBounded(adapted.markdown, overlay, "skill") : adapted.markdown }
  }))
  const catalog = catalogFor([...downloaded].sort())
  const allOutputs = [...outputs.map((item) => ({ ...item, destination: path.join(targetOutputRoot, item.file) })), { markdown: catalog, destination: path.join(targetSkillRoot, "references/components.md") }]
  const extras = present.filter((file) => !downloaded.has(file))
  if (extras.length) throw new Error(`Unexpected generated references: ${extras.join(", ")}`)
  for (const item of allOutputs) {
    if (mode === "--check") {
      const actual = await readFile(item.destination, "utf8").catch(() => "")
      if (actual.replaceAll("\r\n", "\n") !== item.markdown) throw new Error(`Stale/missing local reference: ${item.destination}`)
    } else {
      await mkdir(path.dirname(item.destination), { recursive: true })
      await writeFile(item.destination, item.markdown, "utf8")
    }
  }
  if (mode === "--write") await referenceLock(targetSkillRoot, mode, overlays)
  console.log(`${mode}: ${files.length} documents, ${outputs.reduce((count, item) => count + item.linkCount, 0)} localized component links`)
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  synchronize(process.argv[2]).catch((error) => { console.error(error.message); process.exitCode = 1 })
}
