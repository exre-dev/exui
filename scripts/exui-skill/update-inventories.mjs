import { existsSync } from "node:fs"
import { createRequire } from "node:module"
import { readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const skillRoot = path.join(repoRoot, "skills/exui")
const componentRoot = path.join(repoRoot, "packages/components")
const require = createRequire(path.join(componentRoot, "package.json"))
const ts = require("typescript")
const mode = process.argv[2]
if (process.argv.length !== 3 || !["--write", "--check"].includes(mode)) throw new Error("usage: node scripts/exui-skill/update-inventories.mjs (--write | --check); build Tokens and components first")
const manifest = JSON.parse(await readFile(path.join(componentRoot, "package.json"), "utf8"))
const notice = "<!-- Generated by scripts/exui-skill/update-inventories.mjs. Do not edit by hand. -->"
const posix = (value) => value.replaceAll("\\", "/")
const configFile = path.join(componentRoot, "tsconfig.json")
const rawConfig = ts.readConfigFile(configFile, ts.sys.readFile)
if (rawConfig.error) throw new Error(ts.flattenDiagnosticMessageText(rawConfig.error.messageText, "\n"))
const config = ts.parseJsonConfigFileContent(rawConfig.config, ts.sys, componentRoot)
const entry = path.join(componentRoot, "src/index.ts")
const program = ts.createProgram([entry], { ...config.options, noEmit: true })
const checker = program.getTypeChecker()
const source = program.getSourceFile(entry)
const moduleSymbol = source && checker.getSymbolAtLocation(source)
if (!moduleSymbol) throw new Error("Cannot resolve ExUI public root")

function referenceFor(sourceFile) {
  const name = posix(sourceFile)
  if (/\/(patterns|lib\/forms)\//.test(name) || /\/hooks\/use-form/.test(name)) return "../exui/form.md"
  if (name.includes("glass-seed")) return "../exui/glass.md"
  if (/ex-message/.test(name)) return "../exui/notifications.md"
  if (name.includes("theme-provider")) return "../exui/theme-usage.md"
  const match = name.match(/\/components\/(?:ui|reui)\/([^/.]+)/)
  if (match && existsSync(path.join(skillRoot, "references/components", `${match[1]}.md`))) return `../components/${match[1]}.md`
  if (name.includes("use-file-upload")) return "../components/file-upload.md"
  return "../exui/setup.md"
}

const symbols = checker.getExportsOfModule(moduleSymbol).sort((left, right) => left.name.localeCompare(right.name, "en"))
if (!symbols.length) throw new Error("ExUI export inventory is empty")
const exportLines = symbols.map((symbol) => {
  const resolved = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol
  const declaration = resolved.getDeclarations()?.[0]
  const file = declaration?.getSourceFile().fileName ?? entry
  const kind = resolved.flags & ts.SymbolFlags.Value ? (resolved.flags & ts.SymbolFlags.Type ? "value + type" : "value") : "type"
  return `| \`${symbol.name}\` | ${kind} | [contract](${referenceFor(file)}) |`
})
const exportsMarkdown = [notice, "", "# ExUI public exports", "", `Generated from the current repository package root (${manifest.name}, source manifest version ${manifest.version}); ${symbols.length} names. The version is source metadata, not a statement about a published tarball. This symbol inventory does not define props; read the installed package declarations for the consuming version.`, "", "| Public name | Kind | Related contract |", "| --- | --- | --- |", ...exportLines, ""].join("\n")

const tokensTarget = manifest.exports["./tokens"].import
const tokenFile = typeof tokensTarget === "string" ? tokensTarget : tokensTarget.default
const cssTarget = manifest.exports["./tokens/style.css"]
const cssFile = typeof cssTarget === "string" ? cssTarget : cssTarget.default
const { exuiTokens, componentRecipes } = await import(pathToFileURL(path.join(componentRoot, tokenFile)).href)
function leafPaths(value, prefix) {
  if (!value || typeof value !== "object" || value.kind === "foundation" || value.kind === "semantic") return [prefix]
  return Object.entries(value).flatMap(([key, next]) => leafPaths(next, `${prefix}.${key}`))
}
if (!exuiTokens?.themes || !componentRecipes?.button) throw new Error("Missing built public Token data; rebuild the components package")
const tokenCss = await readFile(path.join(componentRoot, cssFile), "utf8")
const cssNames = [...new Set([...tokenCss.matchAll(/(?:^|[;{])\s*(--[\w-]+)\s*:/g)].map((match) => match[1]))].sort()
if (!cssNames.length) throw new Error("Token stylesheet contains no custom properties")
const section = (title, names) => [`## ${title}`, "", ...names.sort().map((name) => `- \`${name}\``), ""]
const tokenMarkdown = [notice, "", "# ExUI Token and recipe names", "", "Generated from the built public Tokens entry and stylesheet. Names identify built-in data; CSS overrides do not mutate JavaScript objects. Rebuild before refreshing this inventory.", "", ...section("exuiTokens", leafPaths(exuiTokens, "exuiTokens")), ...section("componentRecipes", leafPaths(componentRecipes, "componentRecipes")), ...section("CSS custom properties", cssNames)].join("\n")
for (const [name, content] of [["component-exports.md", exportsMarkdown], ["token-paths.md", tokenMarkdown]]) {
  const destination = path.join(skillRoot, "references/generated", name)
  if (mode === "--check") {
    const actual = await readFile(destination, "utf8").catch(() => "")
    if (actual.replaceAll("\r\n", "\n") !== content) throw new Error(`Stale inventory: ${name}`)
  } else await writeFile(destination, content, "utf8")
}
console.log(`${mode}: ${symbols.length} public exports; ${leafPaths(exuiTokens, "exuiTokens").length} Token paths; ${cssNames.length} CSS properties`)
