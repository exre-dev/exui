  for (const [key, actual, expected] of [['examples', lock.examples?.length, 1264], ['candidate families', lock.families?.length, 86], ['excluded examples', lock.examples?.filter(example => example.family === 'file-upload').length, 10]]) assert(actual === expected, `pinned inventory mismatch ${key}: expected ${expected}, received ${actual}`)
