export function safePath(filename) {
  assert(typeof filename === 'string' && filename.length > 0 && !invalidPathCharacters(filename)
    && !filename.startsWith('/') && filename.split('/').every(part => part && part !== '.' && part !== '..'), `invalid path: ${filename}`)
  return filename
}
function inside(root, filename) {
  safePath(filename)
  const target = path.resolve(root, filename)
  assert(target.startsWith(path.resolve(root) + path.sep), `path escapes root: ${filename}`)
  return target
}
function identityCheck(identity) {
  for (const [key, value] of Object.entries(PINNED_IDENTITY)) assert(identity[key] === value, `invalid pinned identity ${key}: ${identity[key]}`)
  assert(identity.schemaVersion === undefined || identity.schemaVersion === 1, 'invalid schemaVersion')
}
export function sourceHash(bytes, mode = 'text-lf') {
  assert(mode === 'binary' || mode === 'text-lf', `invalid digest mode: ${mode}`)
  return createHash('sha256').update(mode === 'binary' ? bytes : Buffer.from(bytes).toString('utf8').replace(/\r\n/g, '\n')).digest('hex')
}
function ast(text, filename = 'example.tsx') { return ts.createSourceFile(filename, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX) }
export function moduleSpecifiers(text) {
  const values = []
  function visit(node) {
    if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier && ts.isStringLiteralLike(node.moduleSpecifier)) values.push(node.moduleSpecifier.text)
    if (ts.isImportEqualsDeclaration(node) && ts.isExternalModuleReference(node.moduleReference) && node.moduleReference.expression && ts.isStringLiteralLike(node.moduleReference.expression)) values.push(node.moduleReference.expression.text)
    if (ts.isImportTypeNode(node) && ts.isLiteralTypeNode(node.argument) && ts.isStringLiteralLike(node.argument.literal)) values.push(node.argument.literal.text)
    if (ts.isCallExpression(node) && (node.expression.kind === ts.SyntaxKind.ImportKeyword || ts.isIdentifier(node.expression) && node.expression.text === 'require') && node.arguments[0] && ts.isStringLiteralLike(node.arguments[0])) values.push(node.arguments[0].text)
    ts.forEachChild(node, visit)
  }
  visit(ast(text))
  return [...new Set(values)]
}
function stringLiterals(text) {
  const values = []
  function visit(node) { if (ts.isStringLiteralLike(node)) values.push(node.text); ts.forEachChild(node, visit) }
  visit(ast(text)); return values
}
function resolveSource(specifier, owner, paths) {
  const base = specifier.startsWith('@/') ? specifier.slice(2) : path.posix.normalize(path.posix.join(path.posix.dirname(owner), specifier))
  safePath(base)
  const resolved = [base, ...['.ts', '.tsx', '.js', '.jsx', '.json', '/index.ts', '/index.tsx'].map(ext => base + ext)].find(candidate => paths.has(candidate))
  assert(resolved, `unresolved helper ${specifier} from ${owner}`)
  return resolved
}
function digestMode(filename) { return /\.(?:tsx?|jsx?|json|css|md|txt|svg|html|ya?ml|mjs|cjs)$/i.test(filename) ? 'text-lf' : 'binary' }

/** The tree response is explicit so injected/remote truncated inventories cannot become valid locks. */
export async function buildSourceLock({ source, identity = PINNED_IDENTITY, catalog, expectedCounts = { examples: 1264, families: 87, candidates: 1254, candidateFamilies: 86 } }) {
  identityCheck(identity)
  const tree = await source.listTree()
  assert(tree && tree.truncated === false && Array.isArray(tree.paths), 'missing or truncated upstream tree')
  const paths = new Set(); const insensitive = new Set()
  for (const filename of tree.paths) { safePath(filename); assert(!insensitive.has(filename.toLowerCase()), `duplicate upstream path: ${filename}`); paths.add(filename); insensitive.add(filename.toLowerCase()) }
  const mainPaths = [...paths].filter(filename => sourcePattern.test(filename)).sort()
  assert(mainPaths.length, 'missing example sources')
  const metadataPaths = [...paths].filter(filename => filename.startsWith(metadataPrefix) && filename.endsWith('.json') && filename !== `${metadataPrefix}name-index.json`).sort()
  const bytes = new Map()
  if (source.prefetch) await source.prefetch([...mainPaths, ...metadataPaths, 'LICENSE.md'])
  const read = async filename => { assert(paths.has(filename), `missing upstream file: ${filename}`); if (!bytes.has(filename)) bytes.set(filename, Buffer.from(await source.readSource(filename))); return bytes.get(filename) }
  const metadata = new Map()
  for (const filename of metadataPaths) {
    const family = filename.slice(metadataPrefix.length, -5)
    const data = JSON.parse((await read(filename)).toString('utf8'))
    assert(Array.isArray(data.items), `invalid metadata items: ${filename}`)
    for (const item of data.items) {
      if (!item.name?.startsWith('c-')) continue
      assert(!metadata.has(item.name), `duplicate ID ${item.name}: ${filename}`)
      assert(item.categories?.includes(family), `metadata category mismatch ${item.name}: ${filename}`)
      assert(Array.isArray(item.files) && item.files.length, `missing metadata source ${item.name}: ${filename}`)
      const files = item.files.map(file => {
        assert(typeof file.path === 'string' && !file.path.startsWith('/') && !invalidPathCharacters(file.path), `invalid metadata path ${item.name}: ${file.path}`)
        return safePath(path.posix.normalize(`registry-reui/bases/radix/${file.path}`))
      })
      assert(files.includes(`${componentPrefix}${family}/${item.name}.tsx`), `metadata source mismatch ${item.name}: ${filename}`)
      for (const file of files) assert(paths.has(file), `missing metadata file ${item.name}: ${file}`)
      assert(item.meta?.order === undefined || Number.isFinite(item.meta.order), `invalid order ${item.name}: ${filename}`)
      metadata.set(item.name, { family, filename, files, order: item.meta?.order ?? Number(item.name.match(/\d+$/)?.[0]) })
    }
  }
  const graph = new Map(); const external = new Map(); const unresolved = new Map()
  async function dependencies(filename) {
    if (graph.has(filename)) return graph.get(filename)
    const found = new Set(); graph.set(filename, found)
    if (!/\.(?:tsx?|jsx?|mjs|css|json)$/.test(filename)) { await read(filename); return found }
    const text = (await read(filename)).toString('utf8')
    for (const specifier of moduleSpecifiers(text)) if (specifier.startsWith('@/') || specifier.startsWith('.')) found.add(resolveSource(specifier, filename, paths))
    const urls = new Set(); const missingResources = []
    for (const value of stringLiterals(text)) {
      if (/^https?:\/\//.test(value)) urls.add(value)
      if (value.startsWith('/') && !value.startsWith('//')) {
        const asset = `public${value.split(/[?#]/)[0]}`
        if (paths.has(asset)) found.add(asset)
        else if (/\.(?:png|jpe?g|webp|svg|gif|avif|woff2?|mp4|pdf)$/i.test(asset)) missingResources.push({ source: filename, value, reason: 'not present in pinned Git tree' })
      }
    }
    external.set(filename, urls); unresolved.set(filename, missingResources)
    for (const dependency of found) await dependencies(dependency)
    return found
  }
  const examples = []; const ids = new Set()
  for (const filename of mainPaths) {
    const [, family, id] = filename.match(sourcePattern)
    assert(id.startsWith(`c-${family}-`), `source ID/family mismatch ${id}: ${filename}`)
    assert(!ids.has(id), `duplicate source ID ${id}: ${filename}`); ids.add(id)
    const meta = metadata.get(id)
    assert(meta && meta.family === family, `missing or mismatched metadata ${id}: ${filename}`)
    await dependencies(filename)
    const helpers = new Set(); const resources = new Set(); const missing = new Map()
    const walk = current => { for (const item of unresolved.get(current) ?? []) missing.set(`${item.source}:${item.value}`, item); for (const url of external.get(current) ?? []) resources.add(url); for (const dependency of graph.get(current) ?? []) if (dependency !== filename && !helpers.has(dependency)) { helpers.add(dependency); walk(dependency) } }
    walk(filename)
    for (const extra of meta.files.filter(file => file !== filename)) { await dependencies(extra); helpers.add(extra); walk(extra) }
    examples.push({ id, family, source: filename, sourceSha256: sourceHash(await read(filename)), metadata: [meta.filename], helpers: [...helpers].sort(), order: meta.order, externalResources: [...resources].sort(), unresolvedResources: [...missing.values()].sort((a, b) => a.source.localeCompare(b.source) || a.value.localeCompare(b.value)) })
  }
  for (const id of metadata.keys()) assert(ids.has(id), `metadata has no main source ${id}: ${metadata.get(id).filename}`)
  const nameIndex = `${metadataPrefix}name-index.json`
  assert(paths.has(nameIndex), `missing required metadata name-index: ${nameIndex}`)
  const index = JSON.parse((await read(nameIndex)).toString('utf8'))
  const names = Object.keys(index)
  assert(names.length === examples.length && examples.every(example => index[example.id] === example.family), `metadata name-index mismatch: ${nameIndex}`)
  examples.sort((a, b) => a.family.localeCompare(b.family) || compare(a, b))
  const candidateIds = catalog.filter(page => page.group === 'components').map(page => page.id).sort()
  assert(new Set(candidateIds).size === candidateIds.length, 'duplicate catalog family')
  const upstreamFamilies = [...new Set(examples.map(example => example.family))].sort()
  assert(JSON.stringify(upstreamFamilies.filter(family => family !== 'file-upload')) === JSON.stringify(candidateIds), 'catalog/upstream family mismatch')
  if (expectedCounts) {
    const actual = { examples: examples.length, families: upstreamFamilies.length, candidates: examples.filter(example => example.family !== 'file-upload').length, candidateFamilies: candidateIds.length }
    for (const key of Object.keys(expectedCounts)) assert(actual[key] === expectedCounts[key], `inventory mismatch ${key}: expected ${expectedCounts[key]}, received ${actual[key]}`)
  }
  await read('LICENSE.md')
  const needed = new Set(['LICENSE.md', nameIndex, ...examples.flatMap(example => [example.source, ...example.metadata, ...example.helpers])])
  const files = []
  for (const filename of [...needed].sort()) { const mode = digestMode(filename); files.push({ source: filename, sha256: sourceHash(await read(filename), mode), mode }) }
  return { schemaVersion: 1, ...identity, families: candidateIds.map(id => ({ id, examples: examples.filter(example => example.family === id).map(example => example.id) })), examples, files }
}

