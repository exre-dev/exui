  assert(Array.isArray(coverage.examples), 'missing coverage examples')
  const ids = new Set(); const targets = new Set(); const visitedImports = new Set(); const counts = { adapted: 0, gap: 0, excluded: 0, pending: 0, legacy: 0, upstream: 0 }
