function validateLock(lock, catalog) {
  identityCheck(lock); assert(lock.schemaVersion === 1, 'invalid lock schemaVersion')
  assert(Array.isArray(lock.files) && lock.files.length && Array.isArray(lock.examples) && lock.examples.length && Array.isArray(lock.families), 'incomplete source lock')
  const files = new Map(); const targets = new Set()
  for (const file of lock.files) {
    safePath(file.source); assert(hashPattern.test(file.sha256), `invalid SHA: ${file.source}`); assert(file.mode === digestMode(file.source), `invalid canonical digest mode: ${file.source}`)
    assert(!targets.has(file.source.toLowerCase()), `duplicate file: ${file.source}`); targets.add(file.source.toLowerCase()); files.set(file.source, file)
  }
  assert(files.has('LICENSE.md'), 'missing license lock')
  assert(files.has(`${metadataPrefix}name-index.json`), 'missing required metadata name-index lock')
  const examples = new Map()
  for (const example of lock.examples) {
    const match = example.source?.match(sourcePattern)
    assert(match && match[1] === example.family && match[2] === example.id, `invalid source identity ${example.id}: ${example.source}`)
    assert(!examples.has(example.id), `duplicate lock ID ${example.id}: ${example.source}`); examples.set(example.id, example)
    assert(files.get(example.source)?.sha256 === example.sourceSha256, `source hash mismatch ${example.id}: ${example.source}`)
    assert(Number.isFinite(example.order), `invalid order ${example.id}: ${example.source}`)
    assert(Array.isArray(example.metadata) && example.metadata.includes(`${metadataPrefix}${example.family}.json`) && Array.isArray(example.helpers), `missing metadata/helpers ${example.id}: ${example.source}`)
    for (const filename of [...example.metadata, ...example.helpers]) { safePath(filename); assert(files.has(filename), `missing locked helper ${example.id}: ${filename}`) }
  }
  const familyIds = new Set()
  for (const family of lock.families) {
    assert(/^[a-z0-9-]+$/.test(family.id) && family.id !== 'file-upload' && !familyIds.has(family.id), `invalid/duplicate family ${family.id}`); familyIds.add(family.id)
    const expected = lock.examples.filter(example => example.family === family.id).sort(compare).map(example => example.id)
    assert(expected.length && JSON.stringify(family.examples) === JSON.stringify(expected), `family example set/order mismatch ${family.id}`)
  }
  assert(lock.examples.every(example => example.family === 'file-upload' || familyIds.has(example.family)), 'unregistered source family')
  if (catalog) assert(JSON.stringify([...familyIds].sort()) === JSON.stringify(catalog.filter(page => page.group === 'components').map(page => page.id).sort()), 'catalog/lock family mismatch')
  return examples
}
const forbiddenRuntime = /^(?:(?:recharts|@tanstack\/react-table|@tanstack\/table-core|radix-ui|vaul|cmdk|sonner|react-day-picker|react-resizable-panels|embla-carousel-react|react-hook-form|input-otp)(?:$|\/)|@radix-ui\/|@base-ui\/|@hookform\/resolvers(?:$|\/))/
function inspectImports(filename, text, root, visited = new Set()) {
  if (visited.has(filename)) return
  visited.add(filename)
  for (const specifier of moduleSpecifiers(text)) {
    assert(!specifier.startsWith('@/') && !specifier.startsWith('registry') && !specifier.includes('packages/components/') && !specifier.startsWith('@exre/exui/') && !forbiddenRuntime.test(specifier), `forbidden import ${specifier}: ${filename}`)
    if (specifier.startsWith('.')) {
      const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(filename), specifier))
      assert(resolved.startsWith('packages/docs/src/'), `forbidden private import ${specifier}: ${filename}`)
      const dependency = [resolved, ...['.ts', '.tsx', '.js', '.jsx', '.json', '.css', '/index.ts', '/index.tsx'].map(ext => resolved + ext)].find(candidate => existsSync(inside(root, candidate)))
      assert(dependency, `missing imported helper ${specifier}: ${filename}`)
      if (/\.[cm]?[jt]sx?$/.test(dependency)) inspectImports(dependency, readFileSync(inside(root, dependency), 'utf8'), root, visited)
    }
  }
}
