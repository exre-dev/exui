import assert from "node:assert/strict"
import { createHash } from "node:crypto"
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import path from "node:path"
import test from "node:test"
import { adaptDocument, localizeReferences, synchronize } from "./sync-references.mjs"

const files = new Set(["command.md", "command/c-command-1.md", "button.md"])

test("nested examples link to sibling and parent references with fragments", () => {
  const input = "[Command](https://reui.io/components/command.md#examples) [Basic](https://reui.io/components/command/c-command-1.md)"
  const result = localizeReferences(input, "command/c-command-1.md", files)
  assert.equal(result.markdown, "[Command](../command.md#examples) [Basic](./c-command-1.md)")
  assert.equal(result.linkCount, 2)
})

test("bare pages and autolinks become clickable local Markdown links", () => {
  const result = localizeReferences("Page: https://reui.io/components/command\n<https://reui.io/components/button.md>", "command.md", files)
  assert.equal(result.markdown, "Page: [local reference](./command.md)\n[local reference](./button.md)")
})

test("third-party sources stay external while an upstream style query is dropped", () => {
  const result = localizeReferences("[Button](https://reui.io/components/button.md?style=radix-luma#examples) [API](https://ui.shadcn.com/docs/components/radix/button.md)", "command.md", files)
  assert.equal(result.markdown, "[Button](./button.md#examples) [API](https://ui.shadcn.com/docs/components/radix/button.md)")
})

test("an absent local target fails rather than inventing a local file", () => {
  assert.throws(() => localizeReferences("https://reui.io/components/missing.md", "command.md", files), /Missing downloaded target/)
})

test("path traversal cannot turn an upstream component URL into an outside link", () => {
  assert.throws(() => localizeReferences("https://reui.io/components/%2e%2e%2fprivate.md", "command.md", files), /Invalid component path/)
})


test("adaptation removes upstream installation commands but preserves behavior guidance", () => {
  const input = "# Basic\n- MCP: get_example(1)\n\n## Install\n\n```bash\nnpx shadcn@latest add @reui/c-command-1\n```\n\n## About Command\nKeyboard navigation remains documented.\n[Command](https://reui.io/components/command.md)"
  const result = adaptDocument(input, "command/c-command-1.md", files)
  assert.match(result.markdown, /ExUI contracts/)
  assert.match(result.markdown, /Keyboard navigation remains documented/)
  assert.match(result.markdown, /\[Command\]\(\.\.\/command\.md\)/)
  assert.doesNotMatch(result.markdown, /npx shadcn|- MCP:/)
})

test("consumer guidance keeps behavior and API names without registry promotion", () => {
  const input = "# Command\n- Registry item: https://reui.io/r/command.json\n\nReUI patterns preserve keyboard navigation. Use `ReuigetDayKey` when documented.\n[Related layout](https://reui.io/blocks/layout.md)\n"
  const result = adaptDocument(input, "command.md", files)
  assert.match(result.markdown, /preserve keyboard navigation/)
  assert.match(result.markdown, /`ReuigetDayKey`/)
  assert.match(result.markdown, /Related layout/)
  assert.doesNotMatch(result.markdown, /\bReUI\b|reui\.io|Registry item/)
})

const catalog = `<!-- Generated by scripts/exui-skill/sync-references.mjs. -->

# Local component catalog

Use this catalog to choose a family and read its when-to-use guidance. Each family page links its downloaded c-* pattern descriptions. For exact ExUI exports and props, read [ExUI contracts](exui/setup.md) and the [export inventory](generated/component-exports.md).

- [button](components/button.md)
`
const digest = (text) => createHash("sha256").update(text).digest("hex")

async function referenceFixture(t) {
  const root = await mkdtemp(path.join(tmpdir(), "exui-skill-reference-test-"))
  t.after(async () => {
    assert.equal(path.dirname(root), path.resolve(tmpdir()))
    assert.ok(path.basename(root).startsWith("exui-skill-reference-test-"))
    await rm(root, { recursive: true, force: true })
  })
  const skillRoot = path.join(root, "skills/exui")
  const sourceRoot = path.join(root, "resources/components")
  const output = path.join(skillRoot, "references/components")
  await mkdir(output, { recursive: true })
  await mkdir(path.join(skillRoot, "references/generated"), { recursive: true })
  const document = "# Button\n\nA reviewed component reference.\n"
  const lock = { schemaVersion: 1, files: { "button.md": digest(document) }, catalogSha256: digest(catalog) }
  const lockFile = path.join(skillRoot, "references/generated/component-reference-lock.json")
  await writeFile(path.join(output, "button.md"), document)
  await writeFile(path.join(skillRoot, "references/components.md"), catalog)
  await writeFile(lockFile, JSON.stringify(lock))
  return { skillRoot, sourceRoot, output, lockFile, lock, overlays: new Map() }
}

test("ExUI family overlay survives regeneration and is checked without the archive", async (t) => {
  const fixture = await referenceFixture(t)
  fixture.overlays.set("button", "## ExUI capability notes\n\nUse the reviewed Button shape.")
  await mkdir(fixture.sourceRoot, { recursive: true })
  await writeFile(path.join(fixture.sourceRoot, "button.md"), "# Button\n\nUpstream behavior.\n\n## When to use\n\nPress to act.\n")
  await synchronize("--write", fixture)
  const output = await readFile(path.join(fixture.output, "button.md"), "utf8")
  assert.match(output, /Use the reviewed Button shape/)
  assert.match(output, /Upstream behavior/)
  await rm(fixture.sourceRoot, { recursive: true })
  await synchronize("--check", fixture)
  await writeFile(path.join(fixture.output, "button.md"), output.replace(/<!-- exui-capabilities:begin:skill -->[\s\S]*?<!-- exui-capabilities:end:skill -->\n?/, ""))
  await assert.rejects(synchronize("--lock", fixture), /overlay/i)
  await writeFile(path.join(fixture.output, "button.md"), output)
  fixture.overlays.set("button", "## ExUI capability notes\n\nChanged reviewed guidance.")
  await assert.rejects(synchronize("--check", fixture), /overlay/i)
  await assert.rejects(synchronize("--lock", fixture), /overlay/i)
  fixture.overlays.clear()
  await assert.rejects(synchronize("--lock", fixture), /stale.*overlay/i)
})

test("a clean checkout verifies locked references without the downloaded archive", async (t) => {
  await synchronize("--check", await referenceFixture(t))
})

test("offline checks reject modified references and catalogs", async (t) => {
  const fixture = await referenceFixture(t)
  await writeFile(path.join(fixture.output, "button.md"), "# Changed\n")
  await assert.rejects(synchronize("--check", fixture), /reference hash mismatch/i)
  const other = await referenceFixture(t)
  await writeFile(path.join(other.skillRoot, "references/components.md"), "# Changed catalog\n")
  await assert.rejects(synchronize("--check", other), /catalog/i)
})

test("offline checks reject missing and extra reference files", async (t) => {
  const fixture = await referenceFixture(t)
  await rm(path.join(fixture.output, "button.md"))
  await assert.rejects(synchronize("--check", fixture), /reference inventory mismatch/i)
  const other = await referenceFixture(t)
  await writeFile(path.join(other.output, "extra.md"), "# Extra\n")
  await assert.rejects(synchronize("--check", other), /reference inventory mismatch/i)
})

test("write preflights extra generated references before mutating outputs or lock", async (t) => {
  const fixture = await referenceFixture(t)
  await mkdir(fixture.sourceRoot, { recursive: true })
  await writeFile(path.join(fixture.sourceRoot, "button.md"), "# Changed upstream\n\n## When to use\n\nPress.\n")
  await writeFile(path.join(fixture.output, "unexpected.md"), "# Unrelated reference\n")
  const before = await readFile(path.join(fixture.output, "button.md"), "utf8")
  const lock = await readFile(fixture.lockFile, "utf8")
  await assert.rejects(synchronize("--write", fixture), /unexpected generated references/i)
  assert.equal(await readFile(path.join(fixture.output, "button.md"), "utf8"), before)
  assert.equal(await readFile(fixture.lockFile, "utf8"), lock)
})

test("reference locks reject paths outside the reference directory", async (t) => {
  const fixture = await referenceFixture(t)
  fixture.lock.files["../private.md"] = digest("private")
  await writeFile(fixture.lockFile, JSON.stringify(fixture.lock))
  await assert.rejects(synchronize("--check", fixture), /invalid locked reference/i)
})

test("regeneration locks adapted output and still detects stale downloaded sources", async (t) => {
  const fixture = await referenceFixture(t)
  await mkdir(fixture.sourceRoot, { recursive: true })
  const source = path.join(fixture.sourceRoot, "button.md")
  await writeFile(source, "# Button\n\n[Self](https://reui.io/components/button.md)\n")
  await synchronize("--write", fixture)
  await synchronize("--check", fixture)
  const lock = JSON.parse(await readFile(fixture.lockFile, "utf8"))
  assert.equal(lock.files["button.md"], digest(await readFile(path.join(fixture.output, "button.md"), "utf8")))
  await writeFile(source, "# Button\n\nChanged upstream description.\n")
  await assert.rejects(synchronize("--check", fixture), /stale\/missing local reference/i)
})

test("missing locks require explicit adoption instead of silently trusting references", async (t) => {
  const fixture = await referenceFixture(t)
  await rm(fixture.lockFile)
  await assert.rejects(synchronize("--check", fixture), /ENOENT/)
  await assert.rejects(readFile(fixture.lockFile), /ENOENT/)
  await synchronize("--lock", fixture)
  await synchronize("--check", fixture)
})

test("reference hashes tolerate CRLF checkout normalization", async (t) => {
  const fixture = await referenceFixture(t)
  const file = path.join(fixture.output, "button.md")
  await writeFile(file, (await readFile(file, "utf8")).replaceAll("\n", "\r\n"))
  await synchronize("--check", fixture)
})

test("partial archive adds reviewed pages while preserving locked older references", async (t) => {
  const fixture = await referenceFixture(t)
  await mkdir(path.join(fixture.sourceRoot, "trace"), { recursive: true })
  await writeFile(path.join(fixture.sourceRoot, ".partial"), "ReUI revision delta\n")
  await writeFile(path.join(fixture.sourceRoot, "trace.md"), "# Trace\n\n[Step](https://reui.io/components/trace/c-trace-1.md)\n")
  await writeFile(path.join(fixture.sourceRoot, "trace/c-trace-1.md"), "# Step\n\n[Trace](https://reui.io/components/trace.md)\n")
  const older = await readFile(path.join(fixture.output, "button.md"), "utf8")
  await synchronize("--write", fixture)
  await synchronize("--check", fixture)
  assert.equal(await readFile(path.join(fixture.output, "button.md"), "utf8"), older)
  assert.match(await readFile(path.join(fixture.output, "trace.md"), "utf8"), /\.\/trace\/c-trace-1\.md/)
  const lock = JSON.parse(await readFile(fixture.lockFile, "utf8"))
  assert.deepEqual(Object.keys(lock.files), ["button.md", "trace.md", "trace/c-trace-1.md"])
})

test("partial archive refuses tampered older references and broken downloads before any write", async (t) => {
  const fixture = await referenceFixture(t)
  await mkdir(fixture.sourceRoot, { recursive: true })
  await writeFile(path.join(fixture.sourceRoot, ".partial"), "ReUI revision delta\n")
  const source = path.join(fixture.sourceRoot, "trace.md")
  await writeFile(source, "# Trace\n\n[Missing](https://reui.io/components/trace/c-trace-1.md)\n")
  const oldLock = await readFile(fixture.lockFile, "utf8")
  const oldCatalog = await readFile(path.join(fixture.skillRoot, "references/components.md"), "utf8")
  await assert.rejects(synchronize("--write", fixture), /Missing downloaded target/)
  assert.equal(await readFile(fixture.lockFile, "utf8"), oldLock)
  assert.equal(await readFile(path.join(fixture.skillRoot, "references/components.md"), "utf8"), oldCatalog)
  await assert.rejects(readFile(path.join(fixture.output, "trace.md")), /ENOENT/)
  await writeFile(source, "# Trace\n")
  await writeFile(path.join(fixture.output, "button.md"), "# Tampered\n")
  await assert.rejects(synchronize("--write", fixture), /reference hash mismatch/i)
  assert.equal(await readFile(fixture.lockFile, "utf8"), oldLock)
  await assert.rejects(readFile(path.join(fixture.output, "trace.md")), /ENOENT/)
})
